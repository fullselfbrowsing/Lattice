#!/usr/bin/env node
/**
 * Rewrites the rows of Table "tab:bench" in paper/main.tex from
 * paper/bench/results.json so the paper never carries a number the
 * benchmark did not produce. Run after `pnpm bench:receipts`.
 */
import { readFile, writeFile } from "node:fs/promises";

const texPath = new URL("../paper/main.tex", import.meta.url);
const jsonPath = new URL("../paper/bench/results.json", import.meta.url);
const r = JSON.parse(await readFile(jsonPath, "utf8"));
const tex = await readFile(texPath, "utf8");

const fmt = (x) => (Number.isInteger(x) ? String(x) : String(Math.round(x * 1000) / 1000));
const thousands = (n) => n.toLocaleString("en-US");
const { signMs: s, verifyMs: v, oneMiBImage: img, receiptSize: size, tamperSweep: t, replay: rp } = r;
const perReceipt = Math.round(t.mutations / t.receipts);
const classes = Object.keys(t.classes).length;

const rows = [
  `Create a receipt: redact, canonicalize, sign & median ${fmt(s.median)} ms, p95 ${fmt(s.p95)} ms (n=${thousands(s.n)}) \\\\`,
  `Verify a receipt & median ${fmt(v.median)} ms, p95 ${fmt(v.p95)} ms (n=${thousands(v.n)}) \\\\`,
  `Receipt issuance overhead on a run with a 1 MiB image input & ${fmt(img.issuanceOverheadMedianMs)} ms, median of ${img.runSignedMs.n} signed minus ${img.runUnsignedMs.n} unsigned runs \\\\`,
  `Envelope size & ${thousands(size.baseEnvelopeBytes)} bytes with no inputs, plus ${fmt(size.perInputEnvelopeBytes)} bytes per input hash (signed body ${size.baseBodyBytes} bytes, plus ${fmt(size.perInputBodyBytes)}) \\\\`,
  `Tamper sweep & ${thousands(t.rejected)} of ${thousands(t.mutations)} mutations rejected: ${t.receipts} receipts, ${perReceipt} mutations each across ${classes} classes \\\\`,
  `Offline replay & ${rp.outputHashMatched} of ${rp.runs} runs reproduce the signed output hash \\\\`,
];
const block = `% bench-table:begin (generated by scripts/render-bench-table.mjs from paper/bench/results.json, commit ${r.commit})\n${rows.join("\n")}\n% bench-table:end`;
const pattern = /% bench-table:begin[\s\S]*?% bench-table:end/u;
if (!pattern.test(tex)) {
  console.error("[render-bench-table] markers not found in paper/main.tex");
  process.exit(1);
}
const platformLine = `Table~\\ref{tab:bench} reports the run on Node ${r.node} on an ${r.cpu} laptop processor.`;
const next = tex
  .replace(pattern, block)
  .replace(/Table~\\ref\{tab:bench\} reports the run on Node [^\n]*laptop processor\./u, platformLine);
await writeFile(texPath, next, "utf8");
console.log(`[render-bench-table] wrote ${rows.length} rows (commit ${r.commit})`);

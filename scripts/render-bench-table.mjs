#!/usr/bin/env node
/**
 * Rewrites the generated parts of paper/ieee/main.tex from
 * paper/bench/results.json so the paper never carries a number the
 * benchmark did not produce. Run after `pnpm bench:receipts`; this script
 * only reads results.json and never re-runs the benchmark.
 *
 * Generated blocks, each delimited by a begin/end comment pair:
 *   % bench-table:begin ... % bench-table:end        rows of Table "tab:bench"
 *   % bench-prose:begin ... % bench-prose:end        the paragraph after it
 *   % bench-platform:begin ... % bench-platform:end  the appendix sentence
 * Hardware and Node version go in the reproducibility appendix, not the
 * body sentence next to the table.
 */
import { readFile, writeFile } from "node:fs/promises";

const texPath = new URL("../paper/ieee/main.tex", import.meta.url);
const jsonPath = new URL("../paper/bench/results.json", import.meta.url);
const r = JSON.parse(await readFile(jsonPath, "utf8"));
const tex = await readFile(texPath, "utf8");

const fmt = (x) => (Number.isInteger(x) ? String(x) : String(Math.round(x * 1000) / 1000));
const thousands = (n) => n.toLocaleString("en-US");
const { signMs: s, verifyMs: v, oneMiBImage: img, receiptSize: size, tamperSweep: t, replay: rp } = r;
const perReceipt = Math.round(t.mutations / t.receipts);
const classes = Object.keys(t.classes).length;

const rows = [
  `Create a receipt: redact, canonicalize, sign & median ${fmt(s.median)} ms, p95 ${fmt(s.p95)} ms (n=${thousands(s.n)}) \\\\`,
  `Verify a receipt & median ${fmt(v.median)} ms, p95 ${fmt(v.p95)} ms (n=${thousands(v.n)}) \\\\`,
  `Receipt issuance overhead on a run with a 1 MiB image input & ${fmt(img.issuanceOverheadMedianMs)} ms, median of ${img.runSignedMs.n} signed runs minus median of ${img.runUnsignedMs.n} unsigned runs \\\\`,
  `Envelope size & ${thousands(size.baseEnvelopeBytes)} bytes with no inputs, plus ${fmt(size.perInputEnvelopeBytes)} bytes per input hash (signed body ${size.baseBodyBytes} bytes, plus ${fmt(size.perInputBodyBytes)}) \\\\`,
  `Tamper sweep & ${thousands(t.rejected)} of ${thousands(t.mutations)} mutations rejected: ${t.receipts} receipts, ${perReceipt} mutations each across ${classes} classes \\\\`,
  `Offline replay: kept output against the signed output hash & ${rp.outputHashMatched} of ${rp.runs} runs match \\\\`,
];
const block = `% bench-table:begin (generated by scripts/render-bench-table.mjs from paper/bench/results.json, commit ${r.commit})\n${rows.join("\n")}\n% bench-table:end`;
const pattern = /% bench-table:begin[\s\S]*?% bench-table:end/u;
if (!pattern.test(tex)) {
  console.error("[render-bench-table] markers not found in paper/ieee/main.tex");
  process.exit(1);
}

// Tamper classes in the order bench-receipts.mjs applies them. A class the
// table does not know is named by its id so a new class is never dropped.
const perClass = (id) => Math.round(t.classes[id].total / t.receipts);
const classPhrase = (id) => {
  switch (id) {
    case "payload-bit-flip":
      return `${perClass(id)} single-bit flips at random positions in the payload`;
    case "signature-bit-flip":
      return `${perClass(id)} in the signature`;
    case "keyid-unknown":
      return "an unknown key identifier";
    case "keyid-other-valid-key":
      return "a valid but wrong key identifier";
    case "body-kid-swapped":
      return "a swapped body key identifier";
    case "version-downgrade-v1":
      return "a downgrade to the original schema version";
    case "version-removed":
      return "a removed version";
    case "output-hash-dropped":
      return "a dropped output hash";
    case "audience-edited":
      return "an edited audience";
    case "nonce-edited":
      return "an edited nonce";
    case "expiry-extended":
      return "an extended expiry";
    case "keys-reordered":
      return "reordered keys in the payload";
    case "payload-base64url":
      return "a base64url payload";
    case "payload-swapped-between-receipts":
      return "a payload swapped in from another valid receipt";
    default:
      return `the \\code{${id}} class`;
  }
};
const phrases = Object.keys(t.classes).map(classPhrase);
const classList =
  phrases.length > 1 ? `${phrases.slice(0, -1).join(", ")}, and ${phrases[phrases.length - 1]}` : phrases.join("");
const tamperOutcome =
  t.rejected === t.mutations
    ? "Every mutation is rejected by a typed verification failure, and none makes the verifier throw."
    : `${thousands(t.rejected)} of ${thousands(t.mutations)} mutations are rejected; a mutation that verifies or makes the verifier throw counts as not rejected.`;
const replayOutcome =
  rp.outputHashMatched === rp.runs ? `all ${rp.runs} match` : `${rp.outputHashMatched} of ${rp.runs} match`;
const prose = [
  `% bench-prose:begin (generated by scripts/render-bench-table.mjs from paper/bench/results.json, commit ${r.commit})`,
  `Creating a receipt takes a median of ${fmt(s.median)}~ms: the body is small and Ed25519`,
  `signing is fast. Verification takes a median of ${fmt(v.median)}~ms; besides the signature, it`,
  `re-canonicalizes the body and checks the ten failure branches in order. With a 1~MiB image`,
  `on the run, the median signed run takes ${fmt(img.issuanceOverheadMedianMs)}~ms longer than the median unsigned run.`,
  `The signed path adds SHA-256 hashing of the image bytes, for the input hash and the`,
  `lineage root, and receipt creation. A receipt with no inputs is ${thousands(size.baseEnvelopeBytes)} bytes on the wire, and each`,
  `input hash adds about ${fmt(size.perInputEnvelopeBytes)} bytes. The tamper sweep applies ${perReceipt} mutations to each of`,
  `${t.receipts} signed receipts: ${classList}.`,
  `${tamperOutcome} The replay check runs ${rp.runs} runs with distinct outputs through the`,
  `runtime with a signer, materializes each receipt through the artifact loader with the`,
  `kept outputs, replays it offline, and compares the recomputed output hash with the signed`,
  `one; ${replayOutcome}.`,
  `% bench-prose:end`,
].join("\n");
const prosePattern = /% bench-prose:begin[\s\S]*?% bench-prose:end/u;
if (!prosePattern.test(tex)) {
  console.error("[render-bench-table] prose markers not found in paper/ieee/main.tex");
  process.exit(1);
}

const platform = `% bench-platform:begin\nThe benchmark in \\code{paper/bench/results.json} was produced by \\code{scripts/bench-receipts.mjs} on Node ${r.node} (${r.platform}), processor ${r.cpu}, Lattice ${r.lattice}, commit \\code{${r.commit}}. Provider: ${r.provider}.\n% bench-platform:end`;
const platformPattern = /% bench-platform:begin[\s\S]*?% bench-platform:end/u;
if (!platformPattern.test(tex)) {
  console.error("[render-bench-table] platform markers not found in paper/ieee/main.tex");
  process.exit(1);
}
// Replacement functions keep `$` sequences in the generated text literal.
const next = tex
  .replace(pattern, () => block)
  .replace(prosePattern, () => prose)
  .replace(platformPattern, () => platform)
  .replace(
    /Table~\\ref\{tab:bench\} reports the run on Node [^\n]*\./u,
    "Table~\\ref{tab:bench} reports that run. The Node version and processor are in Appendix~\\ref{app:repro}.",
  );
await writeFile(texPath, next, "utf8");
console.log(`[render-bench-table] wrote ${rows.length} rows and the bench paragraph (commit ${r.commit})`);

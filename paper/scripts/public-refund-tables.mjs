import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CASES, PROTOCOL } from "../../eval/public-refund/cases.mjs";
const root = resolve(import.meta.dirname, "../..");
const s = JSON.parse(readFileSync(resolve(root, "eval/public-refund/results/summary.json"), "utf8"));
const verified = JSON.parse(readFileSync(resolve(root, "eval/public-refund/results/verification.json"), "utf8"));
const audit = JSON.parse(readFileSync(resolve(root, "eval/public-refund/results/rubric-audit.json"), "utf8"));
const manifest = JSON.parse(readFileSync(resolve(root, "eval/public-refund/source-manifest.json"), "utf8"));
assert.equal(s.planned, PROTOCOL.plannedRuns);
assert.equal(s.evidenceComplete, verified.rows.filter((r) => r.evidenceOkay).length);
assert.equal(s.strictPass, verified.rows.filter((r) => r.strict).length);
assert.equal(audit.frozenStrict, s.strictPass);
assert.equal(audit.correctedStrict, audit.models.reduce((n, m) => n + m.correctedStrict, 0));
const correctedSource = manifest.sources.find((source) => source.id === audit.caseId);
assert.equal(correctedSource.url, audit.sourceUrl);
assert.equal(correctedSource.pages.find((page) => page.page === 1).textSha256, audit.sourcePageSha256);
const correctedRows = verified.rows.map((entry) => {
  const answers = entry.grade.answers.map((answer) => ({
    ...answer,
    citation: entry.id.startsWith(`${audit.caseId}:`) && answer.id === audit.question
      ? answer.sources.some((source) => audit.correctedAcceptedPages.some((page) => source === `${audit.caseId}-p${page}`))
      : answer.citation,
  }));
  return { ...entry, answers, strict: entry.grade.format && entry.grade.facts && answers.every((answer) => answer.citation) };
});
assert.equal(correctedRows.filter((entry) => entry.strict).length, audit.correctedStrict);
assert.deepEqual(correctedRows.filter((entry, i) => entry.strict !== verified.rows[i].strict).map((entry) => entry.id), audit.affectedRows.map((entry) => entry.id));
for (const model of audit.models) {
  const rows = correctedRows.filter((entry) => entry.id.includes(`:${model.model}:`));
  assert.equal(rows.length, model.planned);
  assert.equal(rows.filter((entry) => entry.strict).length, model.correctedStrict);
  assert.equal(rows.reduce((n, entry) => n + entry.answers.filter((answer) => answer.citation).length, 0), model.correctedCitedAnswers);
}
const m = PROTOCOL.models.map((id) => s.models.find((m) => m.model === id));
assert.ok(m.every(Boolean));
